import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = async (path) => JSON.parse(await readFile(resolve(root, path), "utf8"));
const write = async (path, value) => {
  const target = resolve(root, path);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, value.replace(/\r?\n/g, "\n"), "utf8");
};

const tokens = await readJson("shared/design/tokens.json");
const manifest = await readJson("shared/contracts/provider-manifest.json");
const digest = createHash("sha256")
  .update(JSON.stringify({ tokens, manifest }))
  .digest("hex");

const toKebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const cssLines = [
  "/* Generated by scripts/generate-contracts.mjs. Do not edit. */",
  `/* contract-sha256: ${digest} */`,
  ":root {",
];
for (const [name, value] of Object.entries(tokens.geometry)) cssLines.push(`  --tb-${toKebab(name)}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.spacing)) cssLines.push(`  --tb-space-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.type)) {
  cssLines.push(`  --tb-type-${toKebab(name)}: ${typeof value === "number" ? `${value}px` : value};`);
}
for (const [name, value] of Object.entries(tokens.color)) {
  if (typeof value === "string") cssLines.push(`  --tb-color-${toKebab(name)}: ${value};`);
}
for (const [name, value] of Object.entries(tokens.color.light)) cssLines.push(`  --tb-light-${toKebab(name)}: ${value};`);
for (const [name, value] of Object.entries(tokens.color.dark)) cssLines.push(`  --tb-dark-${toKebab(name)}: ${value};`);
for (const [name, value] of Object.entries(tokens.threshold)) cssLines.push(`  --tb-threshold-${toKebab(name)}: ${value};`);
cssLines.push("}", "");
const css = cssLines.join("\n");

const swiftNumber = (value) => (Number.isInteger(value) ? `${value}` : `${value}`);
const swift = `// Generated by scripts/generate-contracts.mjs. Do not edit.
// contract-sha256: ${digest}
import SwiftUI

enum TokenCueDesignTokens {
    static let trayWidth: CGFloat = ${swiftNumber(tokens.geometry.trayWidth)}
    static let settingsWidth: CGFloat = ${swiftNumber(tokens.geometry.settingsWidth)}
    static let settingsHeight: CGFloat = ${swiftNumber(tokens.geometry.settingsHeight)}
    static let trayRadius: CGFloat = ${swiftNumber(tokens.geometry.trayRadius)}
    static let cardRadius: CGFloat = ${swiftNumber(tokens.geometry.cardRadius)}
    static let controlRadius: CGFloat = ${swiftNumber(tokens.geometry.controlRadius)}
    static let warningThreshold = ${tokens.threshold.normalMaxExclusive}
    static let criticalThreshold = ${tokens.threshold.criticalMinInclusive}
    static let accent = Color(hex: "${tokens.color.accent}")
    static let normal = Color(hex: "${tokens.color.normal}")
    static let warning = Color(hex: "${tokens.color.warning}")
    static let critical = Color(hex: "${tokens.color.critical}")
    static let stale = Color(hex: "${tokens.color.stale}")
    static let lightCanvas = Color(hex: "${tokens.color.light.canvas}")
    static let lightSurface = Color(hex: "${tokens.color.light.surface}")
    static let lightSurfaceRaised = Color(hex: "${tokens.color.light.surfaceRaised}")
    static let lightText = Color(hex: "${tokens.color.light.text}")
    static let lightTextSecondary = Color(hex: "${tokens.color.light.textSecondary}")
    static let darkCanvas = Color(hex: "${tokens.color.dark.canvas}")
    static let darkSurface = Color(hex: "${tokens.color.dark.surface}")
    static let darkSurfaceRaised = Color(hex: "${tokens.color.dark.surfaceRaised}")
    static let darkText = Color(hex: "${tokens.color.dark.text}")
    static let darkTextSecondary = Color(hex: "${tokens.color.dark.textSecondary}")
}

private extension Color {
    init(hex: String) {
        let raw = hex.hasPrefix("#") ? String(hex.dropFirst()) : hex
        let value = UInt64(raw.prefix(6), radix: 16) ?? 0
        self.init(
            .sRGB,
            red: Double((value >> 16) & 0xFF) / 255,
            green: Double((value >> 8) & 0xFF) / 255,
            blue: Double(value & 0xFF) / 255,
            opacity: 1)
    }
}
`;

const providers = JSON.stringify(manifest.providers, null, 2);
const ts = `// Generated by scripts/generate-contracts.mjs. Do not edit.
// contract-sha256: ${digest}
export const TOKENCUE_PROVIDER_MANIFEST = ${providers} as const;
export type TokenCueProviderId = (typeof TOKENCUE_PROVIDER_MANIFEST)[number]["id"];
export const TOKENCUE_PROVIDER_IDS = TOKENCUE_PROVIDER_MANIFEST.map((provider) => provider.id);
`;

const swiftCases = manifest.providers.map((provider) => `        "${provider.id}",`).join("\n");
const swiftManifest = `// Generated by scripts/generate-contracts.mjs. Do not edit.
// contract-sha256: ${digest}
import Foundation

public enum TokenCueProviderContract {
    public static let schemaVersion = 1
    public static let providerIDs: [String] = [
${swiftCases}
    ]
}
`;

await write("shared/design/generated/tokencue.css", css);
await write("apps/windows/apps/desktop-tauri/src/generated/designTokens.css", css);
await write("apps/macos/Sources/TokenCue/Generated/TokenCueDesignTokens.swift", swift);
await write("shared/contracts/generated/providers.ts", ts);
await write("apps/windows/apps/desktop-tauri/src/generated/providerManifest.ts", ts);
await write("apps/macos/Sources/TokenCueCore/Providers/GeneratedTokenCueProviderManifest.swift", swiftManifest);

console.log(`Generated TokenCue contracts (${manifest.providers.length} providers, ${digest.slice(0, 12)}).`);
